"""Write the tissue property tables of the documentation from sonosk.tissues."""

import pathlib

import numpy as np

from sonosk import tissues

OUT = pathlib.Path(__file__).resolve().parent / "guide" / "tissue-table.md"

KEYS = {k: f"[{i + 1}]" for i, k in
        enumerate(sorted(set(tissues.REFERENCES) - {"pending", "model"}))}
HEAD = ("c", "rho", "alpha0", "y", "ba", "k", "cp", "perfusion", "echo")
LABEL = {"c": "c [m/s]", "rho": "rho [kg/m3]", "alpha0": "alpha0 [dB/(cm MHz^y)]",
         "y": "y", "ba": "B/A", "k": "k [W/(m K)]", "cp": "cp [J/(kg K)]",
         "perfusion": "perfusion [mL/(min kg)]", "echo": "echo [dB]"}


def fmt(v):
    if np.isinf(v):
        return "anechoic"
    if abs(v) >= 100:
        return f"{v:.0f}" if v == round(v) else f"{v:.1f}"
    return f"{v:.3g}"


def main():
    lines = ["<!-- generated by docs/make_tables.py from sonosk.tissues; do not edit -->", ""]
    for group in ("shared", "skin", "breast", "prostate", "pelvis", "uterus"):
        names = tissues.names(group)
        if not names:
            continue
        lines += [f"### {group.capitalize()}", ""]
        lines.append("| Tissue | " + " | ".join(LABEL[h] for h in HEAD) + " |")
        lines.append("|" + "---|" * (len(HEAD) + 1))
        for n in names:
            props = tissues.properties(n)
            cells = []
            for h in HEAD:
                v, ref, _ = props[h]
                mark = "*" if ref == "model" else KEYS[ref]
                cells.append(f"{fmt(v)} {mark}")
            lines.append(f"| {n} | " + " | ".join(cells) + " |")
        lines.append("")
    lines += ["### References of the table", ""]
    for k in sorted(tissues.REFERENCES):
        if k in ("pending", "model"):
            continue
        lines.append(f"{KEYS[k]} {tissues.REFERENCES[k]}")
        lines.append("")
    lines += ["`*` modelling choice where no measurement fits; the notes below give the "
              "reason.", ""]
    lines += ["### Notes on each value", ""]
    for n in tissues.names():
        rows = [f"{p}: {note}" for p, (v, ref, note) in tissues.properties(n).items()
                if note]
        extra = tissues.TISSUES[n].get("note")
        if extra:
            rows.insert(0, extra)
        if rows:
            lines.append(f"**{n}**: " + "; ".join(rows) + ".")
            lines.append("")
    OUT.write_text("\n".join(lines))
    print("wrote", OUT)
    csv_path = OUT.parent.parent / "tissues.csv"
    tissues.to_csv(csv_path)
    print("wrote", csv_path)


if __name__ == "__main__":
    main()
